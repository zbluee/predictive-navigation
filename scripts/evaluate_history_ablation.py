
import json
from pathlib import Path

import numpy as np
import torch
from torch.nn import functional as F

from predictive_navigation.models import NavigationRNN
from predictive_navigation.ablations import predict_without_history


CHECKPOINT = Path(
    "outputs/predictive_mlp_seed7_epochs120/best_model.pt"
)

VALIDATION = Path("outputs/datasets/val.npz")


def metrics(logits, targets, start=0):
    logits = logits[:, start:]
    targets = targets[:, start:]

    loss = F.cross_entropy(
        logits.reshape(-1, 3),
        targets.reshape(-1),
    )

    accuracy = (
        logits.argmax(dim=-1) == targets
    ).float().mean()

    return {
        "loss": float(loss.item()),
        "accuracy": float(accuracy.item()),
    }


def main():
    # Only load checkpoints generated by our own training script.
    checkpoint = torch.load(
        CHECKPOINT,
        map_location="cpu",
        weights_only=True,
    )

    model = NavigationRNN(
        hidden_size=checkpoint["hidden_size"],
        head_type="mlp",
    )
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()

    with np.load(VALIDATION, allow_pickle=False) as data:
        observations = torch.from_numpy(
            data["observations"].copy()
        )
        actions = torch.from_numpy(
            data["actions"].copy()
        )

    inputs = observations[:, :-1]
    targets = observations[:, 1:]

    with torch.no_grad():
        normal_logits, _ = model(inputs, actions)

        reset_logits = predict_without_history(
            model, inputs, actions
        )

    # Both methods must agree at t=0, when neither has history.
    torch.testing.assert_close(
        normal_logits[:, 0],
        reset_logits[:, 0],
        atol=1e-6,
        rtol=1e-6,
    )

    results = {
        "normal": metrics(normal_logits, targets),
        "memory_reset": metrics(reset_logits, targets),
        "normal_after_t0": metrics(
            normal_logits, targets, start=1
        ),
        "memory_reset_after_t0": metrics(
            reset_logits, targets, start=1
        ),
    }

    print("Model          | Val loss | Accuracy")
    print("---------------------------------------")

    for name in ("normal", "memory_reset"):
        result = results[name]
        print(
            f"{name:<14} | "
            f"{result['loss']:.4f}   | "
            f"{result['accuracy']:.2%}"
        )

    print("\nExcluding the first time step:")

    for name in ("normal_after_t0", "memory_reset_after_t0"):
        result = results[name]
        print(
            f"{name:<22} "
            f"loss={result['loss']:.4f}, "
            f"accuracy={result['accuracy']:.2%}"
        )

    output = Path(
        "outputs/history_ablation_seed7/summary.json"
    )
    output.parent.mkdir(parents=True, exist_ok=True)

    summary = {
        "checkpoint": str(CHECKPOINT),
        "checkpoint_epoch": checkpoint["best_epoch"],
        "dataset": str(VALIDATION),
        "results": results,
    }

    output.write_text(json.dumps(summary, indent=2) + "\n")
    print(f"\nSaved to {output}")


if __name__ == "__main__":
    main()
